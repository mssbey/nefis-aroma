// Existing catalog is a demo. Images describe the category, never actual packaging.
const conceptImage = (seed: Seed) => '/images/nefisaroma/' + (seed.category === 'nbase' ? 'story/aroma-atolyesi' : 'categories/' + (seed.category === 'diy-kitler' ? (seed.profiles.includes('tutun') ? 'tutun' : seed.profiles.includes('ferah') ? 'ferah' : seed.profiles.includes('kremsi') ? 'tatli-kremsi' : 'mix') : seed.category)) + '.webp';

interface Seed {
  name: string;
  series: string;
  category: CategorySlug;
  subcategory: string;
  collection?: CollectionSlug;
  notes: FlavorNote[];
  profiles: FlavorProfile[];
  short: string;
  long: string;
  price: number; // 10 ml / Standart referans fiyatı
  sale?: number; // indirim oranı 0-1
  badges: BadgeKind[];
  featured?: boolean;
  bestSeller?: boolean;
  newArrival?: boolean;
  taste: TasteRadar;
  form: ProductForm;
  usageRate: string;
  steepTime: string;
  origin: string;
  /** Gerçek ürün fotoğrafı olan seriler için tek sabit görsel (ör. 25 Yüksek Aroma DIY Kit hattı).
   * Verilirse tüm varyant/galeri görselleri prosedürel 4'lü set yerine bu tek dosyayı kullanır. */
  heroImage?: string;
}

const n = (label: string, profile: FlavorProfile): FlavorNote => ({ label, profile });

const VOLUME_FACTOR: Record<VariantVolume, number> = {
  '10ml': 1,
  '30ml': 2.4,
  '60ml': 4.2,
  '100ml': 6.3,
};
const INTENSITY_FACTOR: Record<VariantIntensity, number> = {
  Standart: 1,
  Yoğun: 1.12,
  'Extra Fresh': 1.08,
};

const FORM_TYPE: Record<ProductForm, VariantType> = {
  konsantre: 'Konsantre Aroma',
  shortfill: 'Shortfill',
  'diy-kit': 'DIY Kit',
  baz: 'Konsantre Aroma',
};

function round9(v: number) {
  // ...,90 ile biten premium fiyatlandırma
  return Math.max(1, Math.round(v) - 0.1);
}

function buildVariants(seed: Seed, rnd: () => number): ProductVariant[] {
  const slug = slugify(seed.name);
  const volumes: VariantVolume[] =
    seed.form === 'diy-kit'
      ? ['30ml', '60ml', '100ml']
      : seed.form === 'baz'
        ? ['30ml', '60ml', '100ml']
        : ['10ml', '30ml', '60ml', '100ml'];
  const intensities: VariantIntensity[] =
    seed.form === 'baz'
      ? ['Standart']
      : seed.profiles.includes('ferah') || seed.profiles.includes('mentollu')
        ? ['Standart', 'Extra Fresh']
        : ['Standart', 'Yoğun'];

  const variants: ProductVariant[] = [];
  volumes.forEach((volume, vi) => {
    intensities.forEach((intensity, ii) => {
      const base = seed.price * VOLUME_FACTOR[volume] * INTENSITY_FACTOR[intensity];
      const price = round9(base);
      const onSale = !!seed.sale && (vi + ii) % 2 === 0;
      const oldPrice = onSale ? round9(price / (1 - (seed.sale as number))) : undefined;
      const stockRoll = rnd();
      const stock: StockStatus =
        stockRoll > 0.93 ? 'out-of-stock' : stockRoll > 0.78 ? 'low-stock' : 'in-stock';
      const stockCount =
        stock === 'out-of-stock' ? 0 : stock === 'low-stock' ? 2 + Math.floor(rnd() * 4) : 18 + Math.floor(rnd() * 60);
      variants.push({
        id: `${slug}--${volume}-${slugify(intensity)}`,
        sku: `NA-${seed.category.slice(0, 3).toUpperCase()}-${slug.slice(0, 6).toUpperCase()}-${volume.replace('ml', '')}${intensity[0]}`,
        volume,
        type: FORM_TYPE[seed.form],
        intensity,
        price,
        oldPrice,
        stock,
        stockCount,
        image: conceptImage(seed),
        onSale,
      });
    });
  });
  return variants;
}

